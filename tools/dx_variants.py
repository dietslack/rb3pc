#!/usr/bin/env python3
"""Lets one rb3pc-dx build run every Rock Band 3 Deluxe executable.

Every DX default.xex since 2022 is the same title update 5 build with a few
instructions patched (at most 14, in 9 places), and its data comes from
whichever default.xex is installed anyway. This compares the .text of each
known DX executable (dumped with tools/xexdump) against the one rb3pc-dx is
generated from and writes two files. The first is a codegen config with an
[[instruction_variant]] for each address that differs, listing every word
seen there; the generated code switches on the word actually loaded (see SDK
patch 0023). The second is a C++ header with a hash of each 4 KiB page of the
base .text, those addresses masked out, so rb3pc-dx can tell at boot whether
the installed executable has changes it wasn't built for (src/deluxe.cpp).

Usage: dx_variants.py <base_dump> <out.toml> <out.h> [--exclude A | A-B]...
                      [<other_dump>...]
Dumps are tools/xexdump output directories. --exclude leaves addresses out of
the variants (still masked in the hashes): sites handled by hand-written
hooks, such as the code cave in config/dx/hooks.toml.
"""

import sys
from pathlib import Path

PAGE = 0x1000


def text_of(dump: Path):
    for line in (dump / "sections.txt").read_text().splitlines():
        name, addr, size, _ = line.split()
        if name == ".text":
            return int(addr, 16), (dump / "text.bin").read_bytes()[: int(size, 16)]
    raise SystemExit(f"{dump}: no .text")


def fnv1a64(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main(argv):
    if len(argv) < 4:
        raise SystemExit(__doc__)
    base_dump, out_toml, out_h = Path(argv[1]), Path(argv[2]), Path(argv[3])
    excluded, others = set(), []
    args = iter(argv[4:])
    for arg in args:
        if arg == "--exclude":
            spec = next(args)
            lo, _, hi = spec.partition("-")
            lo = int(lo, 16)
            excluded.update(range(lo, (int(hi, 16) if hi else lo) + 1, 4))
        else:
            others.append(Path(arg))

    start, base = text_of(base_dump)
    variants = {}  # address -> words, base first
    for dump in others:
        addr, text = text_of(dump)
        if addr != start or len(text) != len(base):
            print(f"dx_variants: {dump.name}: .text layout differs, skipped", file=sys.stderr)
            continue
        for i in range(0, len(base), 4):
            if base[i : i + 4] != text[i : i + 4]:
                words = variants.setdefault(start + i, [int.from_bytes(base[i : i + 4], "big")])
                word = int.from_bytes(text[i : i + 4], "big")
                if word not in words:
                    words.append(word)

    masked = bytearray(base)
    for a in set(variants) | excluded:
        masked[a - start : a - start + 4] = b"\0\0\0\0"
    hashes = [fnv1a64(bytes(masked[i : i + PAGE])) for i in range(0, len(masked), PAGE)]

    with open(out_toml, "w") as f:
        f.write("# Generated by tools/dx_variants.py from the DX executables in\n")
        f.write("# game/rb3dx/versions. Do not edit.\n")
        for a in sorted(variants):
            if a in excluded:
                continue
            words = ", ".join(f"0x{w:08X}" for w in variants[a])
            f.write(f"\n[[instruction_variant]]\naddress = 0x{a:08X}\nwords = [{words}]\n")

    with open(out_h, "w") as f:
        f.write("// Generated by tools/dx_variants.py. Do not edit.\n#pragma once\n\n")
        f.write("#include <cstdint>\n\nnamespace rb3pc::dx_reference {\n\n")
        f.write(f"constexpr uint32_t kTextStart = 0x{start:08X};\n")
        f.write(f"constexpr uint32_t kTextSize = 0x{len(base):X};\n")
        f.write(f"constexpr uint32_t kPageSize = 0x{PAGE:X};\n\n")
        f.write("// Words that differ between known DX executables (zeroed before hashing).\n")
        f.write("constexpr uint32_t kMaskedAddresses[] = {\n")
        for a in sorted(set(variants) | excluded):
            f.write(f"    0x{a:08X},\n")
        f.write("};\n\n// FNV-1a 64 of each .text page of the base, masked.\n")
        f.write("constexpr uint64_t kPageHashes[] = {\n")
        for h in hashes:
            f.write(f"    0x{h:016X}ull,\n")
        f.write("};\n\n}  // namespace rb3pc::dx_reference\n")

    print(f"dx_variants: {len(others)} executables, {len(variants)} differing addresses")


if __name__ == "__main__":
    main(sys.argv)
